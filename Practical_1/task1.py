"""
Practical 1: Python Variables, Datatypes and Operators
Task 1: Basic Variable Declaration and Type Checking

This program demonstrates:
- Variable declaration with different data types
- Printing multiple variables
- Checking data types using type() function
"""

# Declare variables with different data types
name = "Alex"  # String variable to store student name
roll_number = 101  # Integer variable to store roll number
cgpa = 3.8  # Float variable to store CGPA

# Print all variables in a single statement
print(name, roll_number, cgpa)

# Check and print the data type of each variable
print(type(name))  # Output: <class 'str'>
print(type(roll_number))  # Output: <class 'int'>
print(type(cgpa))  # Output: <class 'float'>
